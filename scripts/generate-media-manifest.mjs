import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, '..');

const MEDIA_DIR = path.join(projectRoot, 'public', 'media');
const OUTPUT_DIR = path.join(projectRoot, 'src', 'generated');
const MANIFEST_JSON_PATH = path.join(OUTPUT_DIR, 'projectMediaManifest.json');
const MANIFEST_TS_PATH = path.join(OUTPUT_DIR, 'projectMedia.ts');

const IMAGE_EXTENSIONS = new Set(['.jpg', '.jpeg', '.png', '.webp', '.avif', '.gif']);
const VIDEO_EXTENSIONS = new Set(['.mp4', '.webm']);

const INITIAL_PROJECT_SLUGS = [
  'animal-injury',
  'cinematch',
  'paw-rescue'
];

function formatDisplayTitle(filename) {
  const nameWithoutExt = filename.replace(/\.[^/.]+$/, '');
  // Replace hyphens and underscores with spaces and title case words
  return nameWithoutExt
    .replace(/[-_]+/g, ' ')
    .replace(/\b\w/g, (char) => char.toUpperCase());
}

export function generateMediaManifest() {
  // Ensure public/media exists
  if (!fs.existsSync(MEDIA_DIR)) {
    fs.mkdirSync(MEDIA_DIR, { recursive: true });
  }

  // Ensure default project folders exist
  for (const slug of INITIAL_PROJECT_SLUGS) {
    const slugDir = path.join(MEDIA_DIR, slug);
    if (!fs.existsSync(slugDir)) {
      fs.mkdirSync(slugDir, { recursive: true });
    }
  }

  // Discover active project subdirectories inside public/media
  const entries = fs.readdirSync(MEDIA_DIR, { withFileTypes: true });
  const projectDirs = entries
    .filter((entry) => entry.isDirectory() && INITIAL_PROJECT_SLUGS.includes(entry.name))
    .map((entry) => entry.name);

  const manifest = {};

  for (const slug of projectDirs) {
    const projectPath = path.join(MEDIA_DIR, slug);
    const files = fs.readdirSync(projectPath);

    // Identify poster files first (e.g. demo.poster.webp or demo-poster.jpg)
    const posterMap = new Map();
    for (const file of files) {
      const lower = file.toLowerCase();
      const match = lower.match(/^(.+?)[._-]poster\.(jpg|jpeg|png|webp|avif)$/);
      if (match) {
        const baseName = match[1];
        posterMap.set(baseName, `/media/${slug}/${file}`);
      }
    }

    // Filter valid media files (excluding poster-only files and dotfiles)
    const mediaFiles = files.filter((file) => {
      if (file.startsWith('.')) return false;
      const lower = file.toLowerCase();
      if (/^[._-]poster\./i.test(lower) || /[._-]poster\.(jpg|jpeg|png|webp|avif)$/i.test(lower)) {
        return false;
      }
      const ext = path.extname(lower);
      return IMAGE_EXTENSIONS.has(ext) || VIDEO_EXTENSIONS.has(ext);
    });

    // Natural alphanumeric sorting (e.g., 01-cover, 02-home, 10-dashboard)
    mediaFiles.sort((a, b) =>
      a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' })
    );

    const projectItems = mediaFiles.map((filename) => {
      const ext = path.extname(filename).toLowerCase();
      const isVideo = VIDEO_EXTENSIONS.has(ext);
      const nameWithoutExt = filename.replace(/\.[^/.]+$/, '');
      const baseKey = nameWithoutExt.toLowerCase();

      // Look up poster if this is a video
      const poster = isVideo ? posterMap.get(baseKey) : undefined;

      return {
        id: `${slug}-${nameWithoutExt}`.toLowerCase().replace(/[^a-z0-9_-]/g, '-'),
        projectSlug: slug,
        type: isVideo ? 'video' : 'image',
        src: `/media/${slug}/${filename}`,
        filename,
        title: formatDisplayTitle(filename),
        ...(poster ? { poster } : {})
      };
    });

    manifest[slug] = projectItems;
  }

  // Ensure output directory exists
  if (!fs.existsSync(OUTPUT_DIR)) {
    fs.mkdirSync(OUTPUT_DIR, { recursive: true });
  }

  // Write JSON manifest
  const jsonContent = JSON.stringify(manifest, null, 2);
  fs.writeFileSync(MANIFEST_JSON_PATH, jsonContent, 'utf-8');

  // Write TypeScript module
  const tsContent = `// Automatically generated by scripts/generate-media-manifest.mjs
// DO NOT EDIT DIRECTLY. Add screenshots/videos into public/media/<project-slug>/

export type MediaType = 'image' | 'video';

export interface ProjectMediaItem {
  id: string;
  projectSlug: string;
  type: MediaType;
  src: string;
  filename: string;
  title: string;
  poster?: string;
}

export type ProjectMediaManifest = Record<string, ProjectMediaItem[]>;

import manifestData from './projectMediaManifest.json';

export const projectMediaManifest: ProjectMediaManifest = manifestData as ProjectMediaManifest;

export function getProjectMedia(projectSlug: string): ProjectMediaItem[] {
  return projectMediaManifest[projectSlug] || [];
}
`;

  fs.writeFileSync(MANIFEST_TS_PATH, tsContent, 'utf-8');
  console.log(`[media-manifest] Generated media manifest with ${Object.keys(manifest).length} projects.`);
}

// When executed directly via node
if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  generateMediaManifest();
}
